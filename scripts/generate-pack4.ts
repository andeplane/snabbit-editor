import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { createLesson, lessons } from "./pack4-levels";
import type { LevelPackData } from "../src/store/types";
const count=Number(process.argv[2]??5);
if(!Number.isInteger(count)||count<1||count>5)throw new Error("Choose 1–5 lessons");
const file="game-resources/Levels/data/storyData.txt";
const packs=JSON.parse(readFileSync(file,"utf8")) as Record<string,LevelPackData>;
const diagnostic=packs["40"].levels.find(level=>level._id==="4001");
if(!diagnostic)throw new Error("Retain the original diagnostic fixture");
packs["40"].levels=[...lessons.slice(0,count).map(createLesson),diagnostic];
const json=JSON.stringify(packs);
writeFileSync(file,json);writeFileSync(file+".gz",gzipSync(json));
mkdirSync("design/pack4",{recursive:true});
for(const lesson of lessons.slice(0,count))writeFileSync(`design/pack4/${lesson.id}.json`,JSON.stringify(createLesson(lesson),null,2)+"\n");
console.log(`Wrote ${count} introductory levels and retained the diagnostic fixture.`);
